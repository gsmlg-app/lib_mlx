#!/usr/bin/env python3
"""Generate both SwiftPM entry points from one dependency/target definition."""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
DEPENDENCIES = '''        .package(url: "https://github.com/ml-explore/mlx-swift", exact: "0.32.3"),
        .package(url: "https://github.com/ml-explore/mlx-swift-lm", exact: "3.32.3"),
        .package(url: "https://github.com/huggingface/swift-transformers", exact: "1.3.0"),
        .package(url: "https://github.com/apple/swift-nio.git", exact: "2.81.0")'''


def manifest(workspace):
    prefix = 'darwin/lib_mlx/Sources/' if workspace else 'Sources/'
    flutter_dependency = '' if workspace else ',\n        .package(name: "FlutterFramework", path: "../FlutterFramework")'
    runtime_dependencies = '"MlxCore", "MlxServer"' + ('' if workspace else ', .product(name: "FlutterFramework", package: "FlutterFramework")')
    tests = '''        .executableTarget(name: "ProtocolTestHost", dependencies: ["MlxCore", "MlxServer"], path: "Tests/ProtocolTestHost"),
        .testTarget(name: "MlxCoreTests", dependencies: ["MlxCore"], path: "Tests/MlxCoreTests"),
        .testTarget(name: "MlxServerTests", dependencies: ["MlxCore", "MlxServer"], path: "Tests/MlxServerTests"),
        .testTarget(name: "MlxRuntimeTests", dependencies: ["lib_mlx"], path: "Tests/MlxRuntimeTests"),
''' if workspace else ''
    return f'''// swift-tools-version: 6.3
// Generated by tool/package_manifests.py; edit the generator, then regenerate.
import PackageDescription

let package = Package(
    name: "{'lib_mlx_workspace' if workspace else 'lib_mlx'}",
    platforms: [.macOS(.v14), .iOS(.v17), .tvOS(.v17)],
    products: [
        .library(name: "MlxCore", targets: ["MlxCore"]),
        .library(name: "MlxServer", targets: ["MlxServer"]),
        .library(name: "lib-mlx", type: .dynamic, targets: ["lib_mlx"]),
        .library(name: "MlxRuntimeFFI", type: .dynamic, targets: ["lib_mlx"])
    ],
    dependencies: [
{DEPENDENCIES}{flutter_dependency}
    ],
    targets: [
        .target(
            name: "MlxCore",
            dependencies: [
                .product(name: "MLX", package: "mlx-swift"),
                .product(name: "MLXLLM", package: "mlx-swift-lm"),
                .product(name: "MLXLMCommon", package: "mlx-swift-lm"),
                .product(name: "Tokenizers", package: "swift-transformers")
            ],
            path: "{prefix}MlxCore",
            resources: [.process("Resources")]
        ),
        .target(
            name: "MlxServer",
            dependencies: [
                "MlxCore",
                .product(name: "NIOCore", package: "swift-nio"),
                .product(name: "NIOPosix", package: "swift-nio"),
                .product(name: "NIOHTTP1", package: "swift-nio")
            ],
            path: "{prefix}MlxServer"
        ),
        .target(name: "lib_mlx", dependencies: [{runtime_dependencies}],
                path: "{prefix}lib_mlx", publicHeadersPath: "include"),
{tests}    ],
    swiftLanguageModes: [.v5]
)
'''


def main():
    check = '--check' in sys.argv
    for path, workspace in [(ROOT/'Package.swift', True), (ROOT/'darwin/lib_mlx/Package.swift', False)]:
        expected = manifest(workspace)
        if check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(f'Manifest drift: {path}; run python3 tool/package_manifests.py')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
    print('SwiftPM manifests match shared configuration')


if __name__ == '__main__':
    main()
